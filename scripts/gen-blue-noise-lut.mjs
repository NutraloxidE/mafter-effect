/** 64×64 rank-ordered tile LUT を src/runtime/blueNoise64.ts に書き出す（決定論・INV-1）。 */
import { writeFileSync } from "node:fs";

const SIZE = 64;
const n = SIZE * SIZE;
let state = 42;
function rng() {
  state = (state + 0x6d2b79f5) >>> 0;
  let t = Math.imul(state ^ (state >>> 15), 1 | state);
  t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

const ranks = Array.from({ length: n }, (_, i) => i);
for (let i = n - 1; i > 0; i--) {
  const j = Math.floor(rng() * (i + 1));
  [ranks[i], ranks[j]] = [ranks[j], ranks[i]];
}
const lut = new Uint8Array(n);
for (let i = 0; i < n; i++) lut[ranks[i]] = Math.round(((i + 0.5) / n) * 255);

const lines = [];
for (let y = 0; y < SIZE; y++) {
  const row = [];
  for (let x = 0; x < SIZE; x++) row.push(lut[y * SIZE + x]);
  lines.push(row.join(", "));
}

writeFileSync(
  "src/runtime/blueNoise64.ts",
  `// Auto-generated by scripts/gen-blue-noise-lut.mjs — seeded rank tile (INV-1).

export const BLUE_NOISE_SIZE = ${SIZE};

/** row-major ${SIZE}×${SIZE}, rank value 0..255 */
export const BLUE_NOISE_64 = new Uint8Array([
${lines.join(",\n")}
]);
`,
);
console.log("wrote src/runtime/blueNoise64.ts");
